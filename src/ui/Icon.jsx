function resolveIconName(value) {
  let raw = String(value == null ? "" : value).trim();
  if (!raw) return "";
  if (raw.startsWith("fa-") || raw.includes(" fa-") || raw.includes("fa-solid")) {
    raw = raw
      .split(/\s+/)
      .filter((part) => part !== "fa-solid" && part !== "fa-spin")
      .map((part) => (part.startsWith("fa-") ? part.slice(3) : part))
      .join(" ")
      .trim();
  }
  const token = raw.split(/\s+/)[0];
  return LEGACY_ALIASES[token] || token;
}

export function Icon({
  name,
  className = "",
  size = "1em",
  strokeWidth = 2,
  title,
  ...rest
}) {
  const resolved = resolveIconName(name);
  const Component = ICONS[resolved];
  if (!Component) {
    if (import.meta.env.DEV) {
      console.warn(`Unknown icon "${name}"`);
    }
    return null;
  }
  const classes = [
    "ah-icon",
    resolved === "loader-circle" ? "animate-spin" : "",
    className,
  ]
    .filter(Boolean)
    .join(" ");
  return (
    <Component
      className={classes}
      size={size}
      strokeWidth={strokeWidth}
      aria-hidden={title ? undefined : "true"}
      aria-label={title || undefined}
      role={title ? "img" : undefined}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
    </Component>
  );
}
